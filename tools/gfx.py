#!/usr/bin/env python3
"""Game graphics: colour palette and the bird, drawn as text below at 12x12 and
scaled by SCALE (1.5 -> 18x18 on screen, nearest-neighbour).

    python3 tools/gfx.py      -> asm/gfx.inc (included by the assembler)
                                 build/bird.png (preview, 10x zoom)

Edit the BIRD picture or the colours, rerun, then `make`.
Palette index 0 ('.') is the sky: the bird is always drawn over sky, so
"transparent" pixels are simply painted sky colour (no read-back needed).
"""
from pathlib import Path

from png import write_png

ROOT = Path(__file__).resolve().parent.parent


def rgb(hex6: str) -> int:
    """'#RRGGBB' -> RGB565."""
    v = int(hex6.lstrip("#"), 16)
    r, g, b = v >> 16, (v >> 8) & 0xFF, v & 0xFF
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


# char: (name, colour). Order = palette index (max 16).
PALETTE = {
    ".": ("SKY",      "#4EC0CA"),
    "K": ("OUTLINE",  "#3B2E2E"),
    "Y": ("YELLOW",   "#F8D838"),
    "O": ("ORANGE",   "#E89830"),
    "W": ("WHITE",    "#F8F8F8"),
    "R": ("BEAK",     "#F05830"),
    "L": ("LIGHTYEL", "#FCF0A0"),
}

SCALE = 1.5

# Bird facing right, drawn at 12 x 12 (scaled by SCALE in the output).
BIRD = [
    "....KKKKK...",
    "..KKLLYKWWK.",
    ".KLYYYKWWWWK",
    "KYYYYYKWWKWK",
    "KKKKYYKWWKWK",
    "KWWWKYYKWWK.",
    "KWWWWKYYKKKK",
    ".KWWKYYKRRRK",
    "..KKOOKRKKK.",
    "..KOOOOKRRK.",
    "...KKOOOKK..",
    ".....KKK....",
]

# Scene colours used by the drawing code (RGB565 constants in gfx.inc).
SCENE = {
    "C_SKY":       "#4EC0CA",
    "C_PIPE":      "#73BF2E",   # pipe body
    "C_PIPE_LT":   "#9CE659",   # highlight strip
    "C_PIPE_DK":   "#558022",   # shaded edge
    "C_PIPE_EDGE": "#3B2E2E",   # outline
    "C_GRASS":     "#5EE270",
    "C_GRASS_DK":  "#3FA84A",
    "C_DIRT":      "#DED895",
    "C_DIRT_DK":   "#D7A84C",
    "C_BLACK":     "#000000",
    "C_WHITE":     "#FFFFFF",
    "C_RED":       "#FF0000",
    "C_GREEN":     "#00FF00",
    "C_BLUE":      "#0000FF",
    "C_YELLOW":    "#FFFF00",
}


def main() -> None:
    keys = list(PALETTE)
    assert len(keys) <= 16
    assert len(BIRD) == 12 and all(len(r) == 12 for r in BIRD), "bird must be 12x12"
    src = [[keys.index(ch) for ch in row] for row in BIRD]
    size = round(12 * SCALE)
    assert size % 2 == 0 and size * size // 2 <= 256, "sprite must fit draw_bird's 8-bit index"
    idx = [[src[int(y / SCALE)][int(x / SCALE)] for x in range(size)] for y in range(size)]
    colours = [rgb(c) for _n, c in PALETTE.values()]

    packed = []
    for row in idx:
        for a, b in zip(row[0::2], row[1::2]):
            packed.append(a << 4 | b)

    lines = ["; Generated by tools/gfx.py - do not edit, edit gfx.py instead.", ""]
    for name, c in SCENE.items():
        lines.append(f"{name:<12} = ${rgb(c):04X}    ; {c}")
    lines += ["", f"BIRD_W = {size}", f"BIRD_H = {size}", "",
              "; palette: index -> RGB565 high / low byte"]
    lines.append("pal_hi: .byte " + ", ".join(f"${c >> 8:02X}" for c in colours))
    lines.append("pal_lo: .byte " + ", ".join(f"${c & 0xFF:02X}" for c in colours))
    lines.append("; " + "  ".join(f"{i}={n}" for i, (n, _c) in enumerate(PALETTE.values())))
    per_row = size // 2
    lines += ["", f"; bird {size}x{size}, 4 bits per pixel, {per_row} bytes per row, "
              "left pixel in the high nibble", "bird:"]
    for r, row in enumerate(idx):
        b = packed[r * per_row:(r + 1) * per_row]
        lines.append("        .byte " + ", ".join(f"${x:02X}" for x in b)
                     + "    ; " + "".join(keys[i] for i in row))
    # Game colour table: up to 16 colours, each gets a 16-byte latch table in RAM
    # (ctab), so a colour id is id*16 = its offset there. Bird palette first, so
    # bird16 can store the offsets directly.
    game = [(n, c) for n, c in PALETTE.values()] + [
        (n.removeprefix("C_"), SCENE[n]) for n in
        ("C_PIPE_EDGE", "C_PIPE_LT", "C_PIPE", "C_PIPE_DK",
         "C_GRASS", "C_GRASS_DK", "C_DIRT", "C_DIRT_DK")] + [("SCORE", SCENE["C_WHITE"])]
    assert len(game) <= 16 and len({n for n, _c in game}) == len(game), "colour names must be unique"
    lines += ["", "; game colour ids (offset into the 256-byte ctab)", f"NCOL = {len(game)}"]
    for i, (n, c) in enumerate(game):
        lines.append(f"ID_{n:<10} = ${i * 16:02X}    ; {c}")
    for i, (n, c) in enumerate(game):
        lines.append(f"CI_{n:<10} = {i:<2}     ; colour index (lcd2.inc)")
        lines.append(f"GCOL_{i:<8} = ${rgb(c):04X}")
    lines.append("gcol_hi: .byte " + ", ".join(f"${rgb(c) >> 8:02X}" for _n, c in game))
    lines.append("gcol_lo: .byte " + ", ".join(f"${rgb(c) & 0xFF:02X}" for _n, c in game))
    # 12-bit colour (RGB444, COLMOD $53) for the bit-banged build. Each bit costs two
    # latch stores; the "cheap" bit value uses X/Y (8 cycles), the other needs two
    # immediate loads (12 cycles). GMAJ_i = the cheap value chosen for colour i.
    c12 = [((int(c[1:3], 16) >> 4) << 8) | ((int(c[3:5], 16) >> 4) << 4) | (int(c[5:7], 16) >> 4)
           for _n, c in game]
    lines += ["", "; 12-bit colours (RGB444) and their cheap bit value (1 = mostly ones)"]
    for i, v in enumerate(c12):
        lines.append(f"G12_{i:<9} = ${v:03X}")
        lines.append(f"GMAJ_{i:<8} = {1 if bin(v).count('1') >= 7 else 0}")
    lines.append("g12_hi: .byte " + ", ".join(f"${v >> 4:02X}" for v in c12) + "   ; bits 11-4")
    lines.append("g12_lo: .byte " + ", ".join(f"${(v << 4) & 0xFF:02X}" for v in c12) + "   ; bits 3-0 << 4")
    # Compiled bird (bit-bang build): BW2 = 2 sky columns + the sprite, 12 bits/pixel.
    step = 2
    # Per pixel, X/Y hold the cheap pair for that pixel's colour; a colour change costs
    # a 4-byte reload (ldx #/ldy #). Cheap bit = 6 bytes / 8 cycles, other = 10 / 12.
    gmaj = [1 if bin(v).count('1') >= 7 else 0 for v in c12]
    code, cycles, prev = 1, 0, None
    for y in range(size):
        for x in range(size + step):
            ci = 0 if x < step else idx[y][x - step]
            if gmaj[ci] != prev:
                code, cycles, prev = code + 4, cycles + 4, gmaj[ci]
            for k in range(12):
                cheap = (c12[ci] >> (11 - k) & 1) == gmaj[ci]
                code += 6 if cheap else 10
                cycles += 8 if cheap else 12
    assert code <= 0x8000 - 0x0400, f"compiled bird needs {code} bytes, RAM has {0x7C00}"
    lines.append(f"BCODE_SIZE = {code}          ; bytes of compiled bird code (12-bit)")
    lines.append(f"BCODE_CYC  = {cycles}          ; cycles to draw it")
    # Erase spans: after a vertical move of k rows, only the columns the old bird
    # really covered in those k rows need sky. top_l/top_r[k-1] = union of rows 0..k-1,
    # bot_l/bot_r[k-1] = union of the last k rows (sprite columns, before STEP offset).
    spans = [[x for x in range(size) if row[x] != 0] for row in idx]
    def union(rows):
        cols = [x for r in rows for x in spans[r]]
        return (min(cols), max(cols)) if cols else (0, 0)
    tops = [union(range(k)) for k in range(1, size + 1)]
    bots = [union(range(size - k, size)) for k in range(1, size + 1)]
    lines += ["", "; erase spans for a k-row vertical move (index k-1)"]
    lines.append("top_l:  .byte " + ", ".join(str(a) for a, _b in tops))
    lines.append("top_w:  .byte " + ", ".join(str(b - a + 1) for a, b in tops))
    lines.append("bot_l:  .byte " + ", ".join(str(a) for a, _b in bots))
    lines.append("bot_w:  .byte " + ", ".join(str(b - a + 1) for a, b in bots))
    lines += ["", f"; bird {size}x{size}, one byte per pixel = colour id (row-major)", "bird16:"]
    for row in idx:
        lines.append("        .byte " + ", ".join(f"${i * 16:02X}" for i in row))
    (ROOT / "asm" / "gfx.inc").write_text("\n".join(lines) + "\n")

    write_png(ROOT / "build" / "bird.png", [[colours[i] for i in row] for row in idx], scale=10)
    print(f"wrote asm/gfx.inc ({len(packed)} sprite bytes, {len(colours)} colours) "
          f"and build/bird.png")


if __name__ == "__main__":
    main()
